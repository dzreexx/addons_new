# -*- coding: utf-8 -*-
from odoo import _, api, fields, models
from odoo.exceptions import UserError


class StockAnalysisFinalReport(models.Model):
    """One checker-facing Final Report per Generate click.

    Each click on ``Generate Final Report`` (from a preview or a saved
    report) creates a NEW header, so concurrent analyses each get their own
    titled final. ``name`` copies the source title: the saved report name,
    or ``FINAL - <Company> - <DD Mon YYYY HH:MM>`` for unsaved previews
    (same pattern ``action_save_report`` uses).

    Lines are a snapshot of product + final qty at generation time. For
    saved-report sources the snapshot can be refreshed on demand via
    ``action_refresh_from_source`` (true live-link to a transient preview
    is impossible: Odoo vacuums transient rows).
    """

    _name = 'fky.stock.analysis.final.report'
    _description = 'Stock Purchase Final Report'
    _order = 'create_date desc, id desc'
    _rec_name = 'name'

    name = fields.Char(string='Name', required=True)
    company_id = fields.Many2one(
        'res.company', string='Perusahaan', required=True, readonly=True)
    user_id = fields.Many2one(
        'res.users', string='Generated By', readonly=True,
        default=lambda self: self.env.user.id)
    create_date = fields.Datetime(string='Generated At', readonly=True)

    source_report_id = fields.Many2one(
        'fky.stock.analysis.report', string='Source Report', readonly=True,
        ondelete='set null',
        help='Saved report this final was generated from (empty when '
             'generated from an unsaved preview).')
    source_preview_id = fields.Integer(
        string='Source Preview', readonly=True,
        help='Database id of the preview this final was generated from '
             '(transient: the preview itself may be vacuumed later; the '
             'snapshot below survives).')

    line_ids = fields.One2many(
        'fky.stock.analysis.final.line', 'final_id', string='Final Lines')
    line_count = fields.Integer(
        string='Jumlah Baris', compute='_compute_line_count')
    source_mark = fields.Char(
        string='Same-Source Mark', compute='_compute_source_mark',
        help='Which generation this final is among finals from the same '
             'source report (e.g. "Final 2 of 3"). Preview-sourced finals '
             'have no source report and show "From Preview".')

    def _compute_line_count(self):
        for rec in self:
            rec.line_count = len(rec.line_ids)

    @api.depends('source_report_id')
    def _compute_source_mark(self):
        for rec in self:
            if not rec.source_report_id:
                rec.source_mark = _('From Preview')
                continue
            sibs = self.search(
                [('source_report_id', '=', rec.source_report_id.id)],
                order='id')
            pos = sibs.ids.index(rec.id) + 1 if rec.id in sibs.ids else len(sibs) + 1
            rec.source_mark = _('Final %s of %s') % (pos, len(sibs))

    # Float analysis columns copied verbatim from the source line into the
    # final snapshot. Field names are identical on fky.stock.analysis.line
    # and on the transient preview line, so one list drives both paths.
    _SNAPSHOT_FLOAT_FIELDS = (
        'on_hand_qty',
        'incoming_qty',
        'sales_order_qty',
        'average_monthly_sales',
        'target_stock_qty',
        'recommended_purchase_qty',
        'moq_qty',
        'final_qty',
        'months_of_stock',
        'future_months_of_stock',
    )

    @api.model
    def _snapshot_vals(self, line, company):
        """Build the frozen final-line vals for one source line.

        Reads the full analysis field set off ``line`` (a
        :model:`fky.stock.analysis.line` or a preview line — they share
        field names) so the checker-facing final carries the same columns as
        the purchase analysis grid.
        """
        vals = {
            'company_id': company.id if company else False,
            'product_id': line.product_id.id,
            'coverage_months': line.coverage_months or 0,
            'vendor_id': line.vendor_id.id or False,
            'has_components': line.has_components,
            'isi_perdus': line.isi_perdus or 0.0,
        }
        for fname in self._SNAPSHOT_FLOAT_FIELDS:
            vals[fname] = getattr(line, fname, 0.0) or 0.0
        return vals

    @api.model
    def _final_lines(self, lines):
        """Snapshot vals for source lines with a Final Quantity > 0 only."""
        return [self._snapshot_vals(line, line.company_id)
                for line in lines
                if line.product_id and (line.final_qty or 0.0) > 0.0]

    @api.model
    def _check_has_final_lines(self, vals_list):
        if not vals_list:
            raise UserError(
                _('No lines with a final quantity greater than zero. '
                  'Set a Final Quantity on at least one row first.'))

    @api.model
    def create_from_report(self, report):
        """New final header + snapshot from a saved report (same title)."""
        final = self.create({
            'name': report.name or _('Unnamed Report'),
            'company_id': report.company_id.id,
            'source_report_id': report.id,
        })
        vals_list = self._final_lines(report.line_ids)
        self._check_has_final_lines(vals_list)
        for vals in vals_list:
            vals['final_id'] = final.id
        self.env['fky.stock.analysis.final.line'].create(vals_list)
        return final

    def action_refresh_from_source(self):
        """Re-snapshot lines from the linked saved report (live on demand)."""
        self.ensure_one()
        if not self.source_report_id:
            return False
        self.line_ids.unlink()
        vals_list = self._final_lines(self.source_report_id.line_ids)
        self._check_has_final_lines(vals_list)
        for vals in vals_list:
            vals['final_id'] = self.id
        self.env['fky.stock.analysis.final.line'].create(vals_list)
        return True

    def action_view_lines(self):
        """Open this final's lines in the checker list view."""
        self.ensure_one()
        return {
            'name': self.name,
            'type': 'ir.actions.act_window',
            'res_model': 'fky.stock.analysis.final.line',
            'view_mode': 'tree',
            'domain': [('final_id', '=', self.id)],
            'view_id': self.env.ref(
                'fky_stock_management.fky_stock_analysis_final_line_tree').id,
            'search_view_id': self.env.ref(
                'fky_stock_management.fky_stock_analysis_final_line_search').id,
            'context': {'create': False, 'delete': False},
        }


class StockAnalysisFinalLine(models.Model):
    """Frozen snapshot row of a Final Report.

    Carries the same analysis columns as
    :model:`fky.stock.analysis.line` so the checker-facing final shows the
    full picture (on hand, incoming, backorder, average, coverage, target,
    planning, isi perdus, MoQ, vendor, ...), not just the final quantity.
    """

    _name = 'fky.stock.analysis.final.line'
    _description = 'Stock Purchase Final Report Line'
    _order = 'product_name asc, id asc'

    final_id = fields.Many2one(
        'fky.stock.analysis.final.report', string='Final Report',
        ondelete='cascade', required=True)
    company_id = fields.Many2one(
        'res.company', string='Perusahaan', readonly=True)
    product_id = fields.Many2one(
        'product.product', string='Product Name', required=True, readonly=True)

    default_code = fields.Char(string='Code', related='product_id.default_code')
    product_name = fields.Char(
        string='Product Name', related='product_id.display_name')

    internal_category_id = fields.Many2one(
        'internal.category', string='Internal Category', readonly=True,
        compute='_compute_internal_category', store=True,
        help='Kategori internal produk (mis. carburator, CDI, as gear depan).')
    product_brand_id = fields.Many2one(
        'product.brand', string='Brand', readonly=True,
        compute='_compute_product_brand', store=True,
        help='Brand produk dari master produk.')

    on_hand_qty = fields.Float(
        string='Stok Saat Ini', readonly=True,
        help='Stok fisik produk pada saat final dibuat.')
    incoming_qty = fields.Float(
        string='Incoming (PO)', readonly=True,
        help='Pembelian barang yang belum diterima pada saat final dibuat.')
    sales_order_qty = fields.Float(
        string='Backorder', readonly=True,
        help='Penjualan yang belum terkirim pada saat final dibuat.')
    average_monthly_sales = fields.Float(
        string='Average Month', readonly=True,
        help='Rata-rata penjualan per bulan.')
    coverage_months = fields.Integer(
        string='Ketahanan Bulan', readonly=True,
        help='Target ketahanan stok (bulan) yang dipakai untuk produk ini.')
    target_stock_qty = fields.Float(
        string='Target Stok', readonly=True,
        help='average month * ketahanan bulan.')
    recommended_purchase_qty = fields.Float(
        string='Planning Pembelian', readonly=True,
        help='Jumlah yang perlu dibeli (sudah dibulatkan ke kelipatan Isi '
             'Per Dus).')
    isi_perdus = fields.Float(
        string='Isi Per Dus', readonly=True,
        compute='_compute_isi_perdus', store=True,
        help='Jumlah unit per dus dari master produk.')
    moq_qty = fields.Float(
        string='MoQ', readonly=True,
        help='Minimum order quantity yang dipakai saat final dibuat.')
    final_qty = fields.Float(
        string='Final Quantity', readonly=True,
        help='Frozen final quantity snapshot at generation time.')
    months_of_stock = fields.Float(
        string='Ketahanan Stok', readonly=True,
        help='Berapa bulan stok bertahan tanpa memperhitungkan incoming.')
    future_months_of_stock = fields.Float(
        string='Ketahanan Stok + PO', readonly=True,
        help='Berapa bulan stok bertahan setelah memperhitungkan incoming.')
    vendor_id = fields.Many2one(
        'res.partner', string='Vendor Pilihan', readonly=True,
        help='Vendor prioritas (sequence terendah) untuk produk ini.')

    has_components = fields.Boolean(
        string='Punya Komponen', readonly=True,
        help='Technical: dipakai tombol Components supaya tidak perlu '
             'menghitung jumlah komponen. True bila produk punya BoM aktif.')

    # ------------------------------------------------------------------ #
    # Computed helpers
    # ------------------------------------------------------------------ #

    @api.depends('product_id')
    def _compute_internal_category(self):
        has_field = 'internal_category' in self.env['product.product']._fields
        for rec in self:
            if has_field and rec.product_id:
                rec.internal_category_id = rec.product_id.internal_category
            else:
                rec.internal_category_id = False

    @api.depends('product_id')
    def _compute_product_brand(self):
        has_field = 'product_brand' in self.env['product.product']._fields
        for rec in self:
            if has_field and rec.product_id:
                rec.product_brand_id = rec.product_id.product_brand
            else:
                rec.product_brand_id = False

    @api.depends('product_id')
    def _compute_isi_perdus(self):
        has_field = 'isi_perdus' in self.env['product.product']._fields
        for rec in self:
            rec.isi_perdus = rec.product_id.isi_perdus if has_field and rec.product_id else 0.0

    def action_view_components(self):
        """Open the BOM components popup as a read-only reference.

        A final report is a frozen snapshot, so no add-back is offered: the
        wizard is opened without a preview/report line link, which the
        ``fky.stock.bom.wizard`` treats as reference-only (same as the
        dashboard entry point).
        """
        self.ensure_one()
        bom = self.env['fky.stock.analysis.service'].get_first_bom(
            self.product_id)
        wizard = self.env['fky.stock.bom.wizard'].create({
            'product_id': self.product_id.id,
            'company_id': self.company_id.id,
            'bom_id': bom.display_name if bom else '',
            'final_qty': self.final_qty or 0.0,
            'line_ids': self.env['fky.stock.bom.wizard']._component_line_vals(
                bom, self.company_id),
        })
        return {
            'name': _('Product Components'),
            'type': 'ir.actions.act_window',
            'res_model': 'fky.stock.bom.wizard',
            'view_mode': 'form',
            'views': [(self.env.ref(
                'fky_stock_management.view_fky_stock_bom_wizard_form'
            ).id, 'form')],
            'res_id': wizard.id,
            'target': 'new',
            'context': {'form_view_initial_mode': 'edit'},
        }
