# -*- coding: utf-8 -*-
from odoo import api, fields, models


class StockConfig(models.Model):
    _name = 'fky.stock.config'
    _description = 'Stock Alert & Analysis Configuration'
    _rec_name = 'name'

    name = fields.Char(
        string='Name',
        default='Stock Alert & Analysis Settings',
    )

    low_stock_percent = fields.Float(
        string='Low Stock Threshold (%)',
        help=('When the current on-hand quantity drops below this percentage '
              'of the minimum quantity, the product is flagged as Low Stock.'),
        default=80.0,
        required=True,
    )

    urgent_stock_percent = fields.Float(
        string='Urgent Stock Threshold (%)',
        help=('When the current on-hand quantity drops below this percentage '
              'of the minimum quantity, the product is flagged as Urgent.'),
        default=20.0,
        required=True,
    )

    best_seller_months = fields.Integer(
        string='Best Seller (Months)',
        help='Jumlah bulan riwayat penjualan untuk menghitung rata-rata '
             'penjualan Best Seller pada dashboard (contoh: 3 = rata-rata '
             'penjualan dari 3 bulan terakhir).',
        default=3,
    )

    average_months = fields.Integer(
        string='Average Month',
        help='Jumlah bulan riwayat penjualan untuk menghitung rata-rata '
             'penjualan bulanan.',
        default=12,
    )

    stock_coverage_months = fields.Integer(
        string='Ketahanan Bulan',
        help='Target ketahanan stok yang dijaga, dalam bulan.',
        default=3,
    )

    exclude_product_ids = fields.Many2many(
        'product.product',
        string='Permanently Excluded Products',
        help=('These products are never generated by the "Generate Rules" wizard. '
              'Manage them here or directly from the Generate Rules wizard.'),
    )

    on_hand_location_ids = fields.Many2many(
        'stock.location',
        string='Lokasi Stok (On Hand)',
        help=('Lokasi yang dihitung sebagai stok saat ini (mis. GDADR/Stock, '
              'TKADR/Stock, GDANA/Stock, TKANA/Stock). Jika kosong untuk '
              'sebuah perusahaan, semua lokasi internal tetap dipakai '
              '(perilaku lama).'),
    )

    @api.model
    def _get(self):
        """Return the singleton config record, auto-creating it if needed.

        Always falls back to the field defaults so the module stays fully
        functional even when the config record is missing (e.g. after a
        partial upgrade or when the view is opened before any record exists).
        """
        rec = self.search([], limit=1)
        if not rec:
            rec = self.create({})
        return rec

    @api.model
    def open_settings(self):
        """Open the existing singleton config record for editing."""
        return {
            'type': 'ir.actions.act_window',
            'name': 'Stock Alert & Analysis Settings',
            'res_model': self._name,
            'res_id': self._get().id,
            'view_mode': 'form',
            'target': 'new',
            'context': {'form_view_initial_mode': 'edit'},
        }

    def write(self, vals):
        res = super().write(vals)
        if any(f in vals for f in ('low_stock_percent', 'urgent_stock_percent')):
            rules = self.env['fky.stock.rule'].sudo().search([])
            if rules:
                rules._compute_qty()
                rules._flush_qty_fields()
        if 'best_seller_months' in vals:
            rules = self.env['fky.stock.rule'].sudo().search([])
            if rules:
                rules._flush_best_seller(rules._compute_best_seller_values())
        return res